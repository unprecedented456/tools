'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const createAIProtocol = require('../src/ai/protocol.cjs');
const createCourseCore = require('../src/shared/course-core.cjs');
const createDOMAdapter = require('../src/shared/dom.cjs');
const mountPanel = require('../src/ui/panel.cjs');
const composeFeatures = require('../src/bootstrap.cjs');
const createPlatform = require('../src/shared/platform.cjs');
const version = require('../src/version.cjs');
const { validateInterfaces, inspectFactory } = require('./module-contracts.cjs');
const factories = {
  app: require('../src/app.cjs'),
  video: require('../src/video/controller.cjs'),
  ui: require('../src/ui/controller.cjs'),
  ai: require('../src/ai/client.cjs'),
  assignment: require('../src/assignment/controller.cjs'),
  discussion: require('../src/discussion/controller.cjs'),
};
function productionFactory(factory) {
  // 私有测试端口只供Node回归使用，不进入用户安装的脚本。
  return inspectFactory(factory).code;
}
function build() {
  const header = fs.readFileSync(path.join(root, 'src/userscript-header.txt'), 'utf8').trimEnd().replace('@@VERSION@@', version);
  validateInterfaces(factories, createCourseCore());
  const modules = [createAIProtocol.toString(), createCourseCore.toString(), createDOMAdapter.toString(), mountPanel.toString(), composeFeatures.toString(), productionFactory(createPlatform), ...Object.values(factories).map(productionFactory)].join('\n\n');
  return `${header}\n\n// Generated by tools/build.cjs. Edit src/, then rebuild.\n(() => {\n  'use strict';\n\n${modules}\n\n  const features = composeFeatures({ app: createApplication, video: createVideoAutomation, ui: createUI, ai: createAIClient, assignment: createAssignmentAutomation, discussion: createDiscussionAutomation }, createCourseCore(), createDOMAdapter(), mountPanel, createPlatform, ${JSON.stringify(version)});\n  features.ui.connect();\n  features.app.start();\n})();\n`;
}
if (require.main === module) {
  const index = process.argv.indexOf('--out');
  const target = index >= 0 ? path.resolve(process.argv[index + 1]) : path.join(root, 'yuketang-autoplay.user.js');
  fs.writeFileSync(target, build(), 'utf8');
}
module.exports = { build, factories, productionFactory };
